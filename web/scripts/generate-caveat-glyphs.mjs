// Writes src/features/interview/librarian/caveatGlyphs.ts: the outlines of Caveat SemiBold (600, the
// Librarian's hand) for the characters it writes, so each letter can be drawn along its own path rather
// than faded in. Run only when the hand changes; the app itself has no font-parsing dependency.
//
// In an empty folder (the font is OFL-1.1, from @fontsource):
//   npm install opentype.js@1.3.4 @fontsource/caveat@5.3.0
//   node /path/to/web/scripts/generate-caveat-glyphs.mjs /path/to/web/src/features/interview/librarian/caveatGlyphs.ts

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const require = createRequire(join(process.cwd(), "package.json"));
const opentype = require("opentype.js");
const fontFile = require.resolve("@fontsource/caveat/files/caveat-latin-600-normal.woff");
const out = process.argv[2];
if (!out) throw new Error("Give the output file.");

const font = opentype.loadSync(fontFile);
const upm = font.unitsPerEm;

// Everything the Librarian is likely to write: ASCII, Latin-1 letters, curly quotes, dashes, × and ….
const chars = new Set();
for (let code = 33; code < 127; code++) chars.add(String.fromCharCode(code));
for (let code = 0xc0; code <= 0xff; code++) chars.add(String.fromCharCode(code));
for (const char of "‘’“”–—×…") chars.add(char);

const glyphs = {};
for (const char of chars) {
  const glyph = font.charToGlyph(char);
  if (!glyph || glyph.index === 0) continue;
  // y grows downward from the baseline, as in SVG.
  const d = glyph.getPath(0, 0, upm).toPathData(0);
  if (!d) continue;
  glyphs[char] = [Math.round(glyph.advanceWidth), d];
}

const body = `// Generated by web/scripts/generate-caveat-glyphs.mjs from Caveat SemiBold (OFL-1.1). Don't edit by hand.
// Each entry: [advance width, SVG path], in font units, baseline at y = 0, y growing downward.

export const CAVEAT = {
  unitsPerEm: ${upm},
  ascender: ${font.ascender},
  descender: ${font.descender},
  space: ${Math.round(font.charToGlyph(" ").advanceWidth)},
  glyphs: ${JSON.stringify(glyphs)} as Record<string, [number, string]>,
};
`;
writeFileSync(out, body);
console.log(`${Object.keys(glyphs).length} glyphs, ${(body.length / 1024).toFixed(0)} KB`);
